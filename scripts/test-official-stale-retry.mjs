import assert from "node:assert/strict";
import Database from "better-sqlite3";
import { claimStaleRetry, finishStaleRetry, staleRetryDue, listStaleRetryTargets, STALE_RETRY_INTERVAL_MS } from "../collectors/official-stale-retry.mjs";
const db = new Database(":memory:");
db.exec(`CREATE TABLE official_apps(id INTEGER,slug TEXT,enabled INTEGER,app_store_id TEXT);
CREATE TABLE official_plans(id INTEGER,app_id INTEGER);
CREATE TABLE official_regions(id INTEGER,enabled INTEGER);
CREATE TABLE official_prices(plan_id INTEGER,region_id INTEGER,channel TEXT,status TEXT);
INSERT INTO official_apps VALUES(1,'chatgpt',1,'123'),(2,'claude',1,NULL);
INSERT INTO official_plans VALUES(1,1),(2,2);
INSERT INTO official_regions VALUES(1,1),(2,1),(3,0);
INSERT INTO official_prices VALUES(1,1,'web_direct','stale'),(1,2,'web_direct','available'),(1,3,'ios_store','stale'),(2,1,'web_direct','estimated');`);
const now = Date.parse("2026-10-23T00:00:00Z");
assert.equal(listStaleRetryTargets(db).length,1);
assert.equal(staleRetryDue(db,now),true);
assert.equal(claimStaleRetry(db,now),true);
assert.equal(claimStaleRetry(db,now+1),false);
finishStaleRetry(db,now+1000);
assert.equal(staleRetryDue(db,now+1000+STALE_RETRY_INTERVAL_MS-1),false);
assert.equal(staleRetryDue(db,now+1000+STALE_RETRY_INTERVAL_MS),true);
db.exec("UPDATE official_prices SET status='available'");
assert.equal(staleRetryDue(db,now+STALE_RETRY_INTERVAL_MS*2),false);
db.close();
console.log("PASS hourly retry: stale-only targets, enabled region scope, lease, persistent hourly schedule, no work after recovery");
