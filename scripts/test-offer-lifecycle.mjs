import assert from "node:assert/strict";
import { reconcileOffers, verifyMissingShopApiOffers } from "../collectors/offer-lifecycle.mjs";
import { mergeCatalogBySourceId } from "../collectors/persist.mjs";
const at = "2026-10-23T00:00:00Z";
const old = { id: "one", sourceId: "shop", productSlug: "chatgpt-plus", sourceTitle: "ChatGPT Plus 成品号", price: 12, capturedAt: at, lastSeenAt: at, url: "https://wzyp.cn/item/test123", status: "in_stock" };
assert.equal(reconcileOffers([old], [], { complete: false })[0].lifecycle, undefined);
assert.equal(reconcileOffers([old], [], { complete: true })[0].lifecycle, "pending");
const gone = { ...old, lifecycle: "delisted", delistedAt: at };
assert.equal(reconcileOffers([gone], [], { complete: true })[0].lifecycle, "delisted");
assert.equal(reconcileOffers([gone], [{ ...old }], { complete: true })[0].lifecycle, "active");
assert.equal(reconcileOffers([old], [{ ...old, id: "two" }], { complete: false }).length, 2);
const make = () => ({ ok: true, collectionComplete: true, resolvedBase: "https://wzyp.cn", offers: [] });
let result = make();
await verifyMissingShopApiOffers([old], result, { fetchImpl: async () => ({ ok: true, json: async () => ({ code: 0, msg: "商品未上架，如有疑问请联系商家" }) }) });
assert.equal(result.offers[0].lifecycle, "delisted");
result = make();
await verifyMissingShopApiOffers([old], result, { fetchImpl: async () => { throw Error("timeout"); } });
assert.equal(result.offers[0].lifecycle, "pending");
assert.equal(result.offers[0].capturedAt, at);
result = { ...make(), collectionComplete: false };
await verifyMissingShopApiOffers([old], result, { fetchImpl: async () => { throw Error("must not call"); } });
assert.equal(result.offers.length, 0);
const previous = { offers: [gone], sources: [{ id: "shop" }] };
assert.equal(mergeCatalogBySourceId({ previous, rawLastGood: new Map([["shop", { offers: [old] }]]), batchSuccess: [] }).offers[0].lifecycle, "delisted");
assert.equal(mergeCatalogBySourceId({ previous: { offers: [old] }, batchSuccess: [{ sourceId: "shop", offers: [], collectionComplete: true }] }).offers[0].lifecycle, "pending");
console.log("PASS lifecycle: partial/full-empty, tombstone, recovery, explicit delisting, network failure, last-good anti-resurrection");

let calls = 0;
result = make();
await verifyMissingShopApiOffers(Array.from({length: 6}, (_, i) => ({...old, id: String(i)})), result, {limit: 2, fetchImpl: async () => { calls++; return {ok: false}; }});
assert.equal(calls, 2);
assert.equal(result.offers.length, 2);
console.log("PASS bounded detail verification");
